import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { importCoverage } from "../src/review-report/infra/coverage.js";
import { coverageHtml } from "../src/review-report/ui/coverage-html.js";
import { collectReviewReport } from "../src/review-report/infra/collect.js";
import { reportHtml } from "../src/review-report/ui/report-html.js";

test("imports revision-matched coverage and rejects mismatched or dirty snapshots", async t => {
  const root = mkdtempSync(path.join(os.tmpdir(), "verify-coverage-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args: string[]) => execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
  git("init", "-q"); git("config", "user.name", "Test"); git("config", "user.email", "test@example.com");
  writeFileSync(path.join(root, "source.ts"), "export const a = 1;\n"); git("add", "source.ts"); git("commit", "-qm", "base");
  const base = git("rev-parse", "HEAD");
  writeFileSync(path.join(root, "source.ts"), "export const a = 2;\n"); git("commit", "-qam", "target");
  const head = git("rev-parse", "HEAD"), source = "export const a = 2;\n";
  const data = { schemaVersion: 1, collector: { name: "Supercov", version: "4.22.0" }, run: { id: "run_example", exitCode: 0, command: ["npm", "test"], measuredAt: "now" }, comparison: { base, head, workingTree: true }, stale: false, sources: { "source.ts": { source, sha256: createHash("sha256").update(source).digest("hex") } }, tests: [{ id: "one", name: "<test>", file: "source.ts", line: 1, source: "test body", change: "modified", diff: [], outcome: "passed", attribution: "exact", executedLines: [], changedHits: [{ file: "source.ts", line: 1 }] }], setups: [], deletedTests: [], limitations: [], changedLines: [{ file: "source.ts", line: 1, status: "covered", coveringTests: ["one"], context: { file: "source.ts", startLine: 1, endLine: 1, source } }] };
  const report = path.join(root, "coverage.json"); writeFileSync(report, JSON.stringify(data));
  writeFileSync(path.join(root, "supercov-evidence.json"), JSON.stringify({ runId: "run_example", base, head, configurationHashes: { "package.json": null, "package-lock.json": null, "npm-shrinkwrap.json": null, "tsconfig.json": null } }));
  const imported = await importCoverage(root, report, base, head);
  assert.equal(imported.tests[0].name, "<test>");
  const html = coverageHtml(imported);
  assert.match(html, /&lt;test&gt;/); assert.doesNotMatch(html, /<test>/);
  assert.match(html, /Tests covering changes/); assert.match(html, /Changed tests/);
  const review = await collectReviewReport({ repository: root, branch: "feature", head, baseline: base, baselineMethod: "branch-creation-reflog", fingerprint: "", clean: true, staged: [], unstaged: [], untracked: [], commits: [] }, [], report);
  assert.equal(review.sections.testsCoverage.status, "available");
  const combined = reportHtml({ goal: "Example", verdict: "UNKNOWN", review }, root);
  assert.match(combined, /&lt;test&gt;/);
  assert.match(combined, /id="architecture"/);
  await assert.rejects(importCoverage(root, report, head, head), /base/);
  data.sources["source.ts"].source = "loose change"; data.sources["source.ts"].sha256 = createHash("sha256").update("loose change").digest("hex");
  writeFileSync(report, JSON.stringify(data));
  await assert.rejects(importCoverage(root, report, base, head), /committed/);
  const rejected = await collectReviewReport({ repository: root, branch: "feature", head, baseline: base, baselineMethod: "branch-creation-reflog", fingerprint: "", clean: false, staged: [], unstaged: [], untracked: [], commits: [] }, [], report);
  assert.equal(rejected.sections.testsCoverage.status, "unavailable");
  assert.match(rejected.sections.testsCoverage.limitations.join(" "), /committed/);
  data.stale = true; writeFileSync(report, JSON.stringify(data));
  await assert.rejects(importCoverage(root, report, base, head), /stale/i);
});
